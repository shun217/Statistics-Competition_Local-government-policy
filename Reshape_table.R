# 5.2 議会議員の女性割合に欠損値がある場合は、その地域の議会議員（補欠選挙、再選挙を除く）の女性割合の平均を入れる
mean_f <- tapply(sub_c$女性割合, sub_c$地域コード, mean, na.rm = TRUE)

