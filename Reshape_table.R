# 5.3 残った欠損をKNN（k=5）で埋める
# 数値変数（年齢平均値・新人割合・無所属割合）は0-1に正規化した差の絶対値、
# カテゴリ変数（都道府県・地域）は一致0・不一致1を距離とし、変数間の平均をとる
norm01 <- function(x) (x - min(x, na.rm = TRUE)) / (max(x, na.rm = TRUE) - min(x, na.rm = TRUE))

num <- sapply(df_c[, c("年齢平均値", "新人割合", "無所属割合")], norm01)
na_i <- which(is.na(df_c$女性割合))
ok_i <- which(is.na(df_c$女性割合) == FALSE)

k <- 5
for (i in na_i) {
  d <- rowMeans(cbind(abs(sweep(num[ok_i, ], 2, num[i, ])),
                      df_c$都道府県[ok_i] != df_c$都道府県[i],
                      df_c$地域[ok_i] != df_c$地域[i]), na.rm = TRUE)
  df_c$女性割合[i] <- mean(df_c$女性割合[ok_i][order(d)[1:k]])
}

colSums(is.na(df_c))

