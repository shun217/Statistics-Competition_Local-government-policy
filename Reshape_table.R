# 5.1 年齢中央値・年齢最小値・年齢平均値・新人割合・65歳以上割合・自民公明割合・共産社民割合・無所属割合の欠損を、
# その地域の議会議員（補欠選挙、再選挙を除く）の平均で埋める
age_vars <- c("年齢中央値", "年齢最小値", "年齢平均値", "新人割合", "X65歳以上割合","自民公明割合","共産社民割合","無所属割合")

